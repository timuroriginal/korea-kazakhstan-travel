// Adapt the reviewed Turkistan package without promoting reserves or unknown facts.
import fs from 'node:fs/promises';
const input=JSON.parse(await fs.readFile(new URL('../data/turkistan-city.json',import.meta.url),'utf8'));
const pair=(ru,ko)=>({ru,ko});
const sourceById=new Map(input.sources.map(s=>[s.id,s]));
const places=input.places.filter(p=>p.decision!=='reserve').map(p=>({
  id:p.id,destination:p.destination,name:p.name,local:p.local,latin:p.id.replace('turkistan-','').replaceAll('-',' '),
  category:p.category,group:p.group,decision:p.decision,copy:p.copy,
  address:p.addressLocal,hours:p.visitor.hours?.ru||null,price:p.visitor.price?.ru||null,
  access:p.visitor.access?.ru||null,
  visitor:{...p.visitor,access:p.visitor.access||pair('Условия посещения пока подтверждены не полностью.','방문 조건이 아직 모두 확인되지는 않았습니다.')},
  visit:p.visit,orderCards:p.orderCards||[],checkedAt:input.checkedAt,
  sources:p.sourceIds.map(id=>sourceById.get(id))
}));
const ids=new Set(places.map(p=>p.id));
if(ids.size!==9||places.length!==9)throw Error('Expected 9 public places and 1 private reserve');
const sections={arrival:'Прибытие',city:'Городской транспорт',outings:'Выезды',language:'Язык',stay:'Проживание',food:'Еда'};
const practical=input.practical.map(p=>({id:'turkistan-'+p.id,section:sections[p.id],title:p.title.ru,titleKo:p.title.ko,
 copy:{answer:p.text,detail:pair('','')},sources:p.sourceIds.map(id=>sourceById.get(id))}));
const routes=input.routes.flatMap(r=>[
 ...r.placeIds.map(placeId=>({placeId,optional:false})),
 ...(r.optionalPlaceIds||[]).filter(id=>ids.has(id)).map(placeId=>({placeId,optional:true}))
].map((stop,index)=>({id:r.id,day:1,order:index+1,...stop,status:r.status,copy:{title:r.title,note:index===0?r.text:pair('','')}})));
const data={copy:{intro:input.city.lead,overview:input.city.overview,duration:input.city.duration,seasons:input.city.seasonAdvice,audience:input.city.tripType},
 nearbyTitle:pair('Исторические выезды','시외 역사 유적'),
 nearbyCopy:pair('Сауран и Отрар относятся к разным направлениям. Выберите один выезд. Готовая поездка с возвращением пока не подготовлена.','사우란과 오트라르는 다른 방향입니다. 외곽 일정은 한 방향으로 고르는 편이 좋습니다. 돌아오는 교통편까지 포함한 코스는 아직 준비되지 않았습니다.'),
 visitorNote:pair('У загородных мест пока нет готового обратного транспорта. У музеев и отдельных услуг есть неподтверждённые условия билетов и языка.','외곽 방문지의 귀환 교통편은 아직 준비되지 않았습니다. 박물관과 개별 서비스의 입장권 및 언어 조건 중 확인되지 않은 부분이 있습니다.'),
 places,practical,routes,seasons:input.seasons.map(s=>({period:s.title,conditions:s.text,plan:pair('','')})),
 editorialDate:input.checkedAt,languageReview:'pending-native-review'};
function validatePairs(value,path=''){
 if(!value||typeof value!=='object')return;
 if('ru' in value||'ko' in value){
   if(typeof value.ru!=='string'||typeof value.ko!=='string'||/[\u2013\u2014]/.test(value.ru+value.ko)||/[А-Яа-яЁё]/.test(value.ko))throw Error('Invalid language pair '+path);
 }else for(const [k,v] of Object.entries(value))validatePairs(v,path+'.'+k);
}
for(const p of places){
 if(p.destination!=='turkistan'||!['culture','museums','walks','food'].includes(p.category))throw Error('Invalid place '+p.id);
 if(p.sources.some(s=>!s?.url))throw Error('Missing source '+p.id);
 for(const key of ['hours','price'])if(Boolean(p[key])!==Boolean(p.visitor[key]))throw Error('Unknown fact changed '+p.id+'.'+key);
 validatePairs(p.copy,p.id+'.copy');validatePairs(p.visitor,p.id+'.visitor');validatePairs(p.visit,p.id+'.visit');
}
for(const r of routes)if(!ids.has(r.placeId))throw Error('Route references reserve '+r.placeId);
if(practical.some(p=>!p.section))throw Error('Unknown practical section');
await fs.writeFile(new URL('../assets/turkistan-data.js',import.meta.url),'// Generated by scripts/import-turkistan.mjs. Editorial reserve excluded.\nexport const turkistanContent = '+JSON.stringify(data,null,2)+';\n');
console.log(`Prepared ${places.length} Turkistan places and ${input.routes.length} route sequences.`);
