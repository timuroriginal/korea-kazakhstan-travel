// Adapt reviewed Aktau copy. Reserves and tour prices are not admission data.
import fs from 'node:fs/promises';
const input=JSON.parse(await fs.readFile(new URL('../data/aktau-city.json',import.meta.url),'utf8'));
const pair=(ru,ko)=>({ru,ko});
const sourceById=new Map(input.sources.map(s=>[s.id,s]));
const places=input.places.filter(p=>p.decision!=='reserve').map(p=>({
 id:p.id,destination:'aktau',name:p.name,local:p.local,latin:p.id.replace('aktau-','').replaceAll('-',' '),
 category:p.category,group:p.group,decision:p.decision,copy:p.copy,address:p.addressLocal,
 hours:p.visitor.hours?.ru||null,price:p.visitor.price?.ru||null,access:p.visitor.access?.ru||null,
 visitor:p.visitor,visit:p.visit,
 orderCards:(p.localPhrases||[]).map(f=>({label:f.label,explanation:f.explanation,localText:f.text})),
 checkedAt:input.checkedAt,sources:[]
}));
const ids=new Set(places.map(p=>p.id));
if(places.length!==12||ids.size!==12)throw Error('Expected 12 public candidates');
const sections={arrival:'Прибытие',city:'Городской транспорт',outings:'Выезды',language:'Язык',stay:'Проживание',food:'Еда'};
const practical=input.practical.map(p=>({id:p.id,section:sections[p.id.replace('aktau-','')],title:p.title.ru,titleKo:p.title.ko,
 copy:{answer:p.text,detail:pair('','')},sources:[]}));
const routes=input.routes.flatMap(r=>[...r.stopIds.map(placeId=>({placeId,optional:false})),...r.optionalStopIds.map(placeId=>({placeId,optional:true}))].map((stop,index)=>({
 id:r.id,day:r.days===2&&index>0?2:1,order:index+1,...stop,status:r.status,
 copy:{title:r.title,note:index===0?r.text:pair('','')}
})));
const data={copy:{intro:input.overview.tagline,overview:input.overview.body,duration:input.overview.duration,seasons:input.overview.seasonAdvice,audience:input.overview.tripType},
 nearbyTitle:pair('Ландшафты и святыни Мангистау','망기스타우의 지형과 성지'),
 nearbyCopy:pair('Это отдельные автомобильные выезды из Актау. Сравните направление, пешую нагрузку, понятный язык сопровождения и возвращение.','악타우에서 차량으로 떠나는 별도 여행입니다. 방향과 걷는 부담, 이해할 수 있는 동행 언어와 귀환을 함께 비교하세요.'),
 visitorNote:pair('Дальние выезды пока не подготовлены для гостя без английского. На Скальной тропе не подтверждён полный проход. Пляжный день с готовыми условиями пока не предлагается.','영어를 모르는 방문객을 위한 장거리 여행은 아직 준비되지 않았습니다. 바위 산책로 전체 통과도 확인되지 않았으며 입장 조건이 정해진 해변 일정은 아직 제안하지 않습니다.'),
 places,practical,routes,seasons:input.seasons.map(s=>({period:s.title,conditions:s.conditions,plan:pair(s.plan.ru+' '+s.limits.ru,s.plan.ko+' '+s.limits.ko)})),
 editorialDate:input.checkedAt,languageReview:'pending-native-review'};
function pairs(v,path=''){
 if(!v||typeof v!=='object')return;
 if('ru'in v||'ko'in v){if(typeof v.ru!=='string'||typeof v.ko!=='string'||/[\u2013\u2014]/.test(v.ru+v.ko)||/[А-Яа-яЁё]/.test(v.ko)||/[가-힣]/.test(v.ru))throw Error('Invalid copy '+path);}
 else for(const [k,x]of Object.entries(v))pairs(x,path+'.'+k);
}
for(const p of places){
 if(!['water','mountains','culture','food'].includes(p.category)||input.places.find(x=>x.id===p.id).sourceIds.some(id=>!sourceById.get(id)?.url))throw Error('Invalid place '+p.id);
 pairs(p.copy,p.id);pairs(p.visitor,p.id);pairs(p.visit,p.id);
}
for(const r of routes)if(!ids.has(r.placeId))throw Error('Reserve or missing route stop');
if(practical.some(p=>!p.section))throw Error('Missing practical section');
if(places.find(p=>p.id==='aktau-bozzhyra').price!==null)throw Error('Tour price became admission');
await fs.writeFile(new URL('../assets/aktau-data.js',import.meta.url),'// Generated by scripts/import-aktau.mjs. Reserves excluded.\nexport const aktauContent = '+JSON.stringify(data,null,2)+';\n');
console.log(`Prepared ${places.length} Aktau places and ${input.routes.length} route sequences.`);
